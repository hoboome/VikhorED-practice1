"""Простой лексический разбор строки ввода."""


def tokenize(line):
    """Разделить строку на слова по пробельным символам.

    Первое слово — имя команды, остальные — её аргументы.
    Пустая строка даёт пустой список.
    """
    return line.split()


def split_command(line):
    """Вернуть пару (команда, аргументы) или (None, []) для пустой строки."""
    words = tokenize(line)
    if not words:
        return None, []
    return words[0], words[1:]
